"use client";

/**
 * Короткий отклик телом в моменты, когда что-то случилось.
 *
 * Три правила из навыка: причина должна быть очевидна, отклик должен совпадать
 * по кадру с видимым изменением, и его не должно быть много. Поэтому здесь
 * ровно два вида и вызываются они только там, где событие необратимо: иконка
 * легла в папку, ставка принята.
 *
 * Работает на Android; iOS Safari Vibration API не поддерживает, и это не
 * повод его не звать - там просто ничего не произойдёт.
 */
function buzz(pattern: number | number[]): void {
  if (typeof navigator === "undefined") return;
  // Кому меньше движения, тому и меньше тряски: настройка про вестибулярный
  // дискомфорт, а вибрация - из того же ряда.
  if (window.matchMedia?.("(prefers-reduced-motion: reduce)").matches) return;
  navigator.vibrate?.(pattern);
}

/** Щелчок: что-то встало на место. */
export function tapped(): void {
  buzz(8);
}

/** Подтверждение: обязательство принято и назад не берётся. */
export function committed(): void {
  buzz([12, 40, 12]);
}
