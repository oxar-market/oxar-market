/**
 * Разметка футболки: где на ней лежат места под нанесение.
 *
 * Пятнадцать мест сеткой на переде, три в ряд и пять рядов, пронумерованы
 * слева направо и сверху вниз. Спина пустая намеренно: печать будет только
 * спереди, и рисовать сзади рамки значило бы обещать то, чего не напечатают.
 *
 * Числа сняты с самой модели лучами, а не подобраны на глаз. Луч летит
 * горизонтально из точки на заданном угле к оси, поэтому перёд футболки для
 * него - почти плоскость: на высотах 0.42-0.70 точка касания стоит на
 * z = 0.122-0.128 и нормаль смотрит на зрителя (nz от 0.94 до 1.00). Отсюда
 * два предела сетки.
 *
 * Снизу - 0.42. Ниже ткань уходит раструбом и нормаль заваливается: на 0.34
 * под углом 24 градуса она даёт уже 0.75, и рамка встаёт косо.
 *
 * Сверху - 0.70. Выше начинается плечо, перёд уходит назад (z падает с 0.122
 * на 0.109 к 0.76 и на 0.092 к 0.82), и верхний ряд перегнуло бы через плечо.
 *
 * По ширине - 21 градус на колонку. На этом угле точка стоит на x = 0.048, а
 * нормаль ещё честная; дальше 32 градусов начинается бок, и там нормаль
 * рушится до 0.68.
 *
 * Коды обязаны совпадать с каталогом в базе (миграция tee_grid) - это
 * проверяет тест рядом.
 */

export type Spot = {
  /** Тот же код, что в thing_spots. По нему место на вещи находит свой лот. */
  code: string;
  label: string;
  /** Высота на вещи: 0 - низ габарита, 1 - верх. */
  height: number;
  /**
   * Угол вокруг оси: 0 - к зрителю, 90 - вправо.
   *
   * Луч летит горизонтально из точки на этом угле к оси, поэтому точка
   * попадания лежит на той же прямой. На плоской грани это даёт сдвиг вдоль
   * неё: колонку сетки можно задать углом, не заводя третью координату.
   */
  azimuth: number;
  /** Размер пятна на поверхности, в единицах модели. */
  size: [number, number];
};

/**
 * Клетка сетки. Чуть шире, чем выше, и это не небрежность: по ширине перёд
 * даёт 0.065 на колонку, а по высоте пять рядов делят 0.19 на всех, и ряд
 * выше 0.046 уже не влезает. Логотипы к тому же чаще шире себя, чем выше.
 */
const CELL: [number, number] = [0.066, 0.043];

/** Колонки слева направо. */
const COLUMNS = [-34, 0, 34];
/** Ряды сверху вниз. */
const ROWS = [0.71, 0.63, 0.55, 0.47, 0.39];

export const SPOTS: Spot[] = ROWS.flatMap((height, row) =>
  COLUMNS.map((azimuth, column) => {
    const number = row * COLUMNS.length + column + 1;
    const label = String(number).padStart(2, "0");
    return { code: `slot_${label}`, label, height, azimuth, size: CELL };
  }),
);

/**
 * Глубина коробки, которой декаль вырезается из поверхности. Было 0.12, и на
 * этом боковые пятна заворачивались на перёд: коробка на боку захватывала и
 * переднюю поверхность тоже, потому что там ткань круто уходит за угол. Ткань
 * тонкая, ей хватает малого.
 */
export const DECAL_DEPTH = 0.07;

/**
 * Чем перекрасить модель. Она приходит с запечённой текстурой чужого демо, а
 * нам нужна чистая вещь: на ней читаются наши места, а не чужой принт. Белый
 * не чистый, а с каплей серого: на чистом белом под этой выдержкой пропадают
 * складки, а вместе с ними и ощущение вещи.
 */
export const REPAINT = { color: 0xf1f2f5, roughness: 0.92 };

/**
 * Поля рамки места - доля от короткой стороны.
 *
 * Число одно на три места: по нему рисуется сам пунктир, по нему же
 * вписывается креатив и по нему же считаются углы мест для фото-режима.
 * Разойдись они - и обводка выбранного места перестала бы совпадать с
 * пунктиром, а напечаталось бы не то, что обведено.
 */
export const FRAME_PAD = 0.06;

/** Скругление углов рамки, той же долей. */
export const FRAME_ROUND = 0.12;
