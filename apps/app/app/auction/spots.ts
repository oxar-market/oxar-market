/**
 * Разметка футболки: где на ней лежат места под нанесение.
 *
 * Числа сняты с самой модели лучами, а не подобраны на глаз, и держатся на
 * трёх правилах.
 *
 * Первое: рукав начинается выше 0.55 роста. Горизонтальный луч на 90 градусах
 * попадает в торс, пока высота ниже, и в рукав, когда выше - на 0.6 точка
 * касания скачет с x=0.14 на x=0.27. Рукава на 78 градусах давали косую метку
 * под мышкой: там луч идёт по касательной (совпадение нормали и луча 0.28
 * против 0.97 на 98 градусах). Поэтому рукава здесь на 98.
 *
 * Второе: ниже 0.34 роста ткань уходит раструбом, и нормаль заваливается вниз -
 * на высотах 0.24-0.30 она даёт до -0.5 по вертикали, и рамка вставала косо.
 * Поэтому у подола зон нет вовсе, нижние стоят на 0.42-0.47.
 *
 * Третье: форм всего три - крупная печать, квадрат под логотип и полоска на
 * загривке. Перёд и спина устроены одинаково: печать, под ней пара квадратов,
 * ниже ничего. Разнобой размеров читался как случайно разбросанные пятна, а
 * одинаковый квадрат - как место под логотип.
 *
 * Боков в списке нет намеренно: реклама на талии не видна ни на фото, ни в
 * жизни, потому что там рука.
 *
 * Коды обязаны совпадать с каталогом в базе (миграция superteam_tee) - это
 * проверяет тест рядом.
 */

export type Spot = {
  /** Тот же код, что в thing_spots. По нему место на вещи находит свой лот. */
  code: string;
  label: string;
  /** Высота на вещи: 0 - низ габарита, 1 - верх. */
  height: number;
  /**
   * Угол вокруг оси: 0 - к зрителю, 90 - вправо.
   *
   * Луч летит горизонтально из точки на этом угле к оси, поэтому точка
   * попадания лежит на той же прямой. На плоской грани это даёт сдвиг вдоль
   * неё: место можно двигать вбок, не заводя третью координату.
   */
  azimuth: number;
  /** Размер пятна на поверхности, в единицах модели. */
  size: [number, number];
};

/** Место под логотип на спине, в единицах модели. */
