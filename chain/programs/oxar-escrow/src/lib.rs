/// Эскроу OXAR: торги, в которых ставка обеспечена деньгами.
///
/// Продаётся вещь целиком, а не место по отдельности. Торг открывается один на
/// футболку, места вешаются на него, и закрываются они все в одну и ту же
/// секунду: срок живёт в торге, а не в месте. Ставка на любое место двигает
/// конец всей вещи - иначе на соседнем месте можно было бы выиграть по
/// таймеру, пока внимание приковано к одному.
///
/// Один путь через пять инструкций. Продавец открывает торг вещи, потом её
/// места. Участники ставят, и деньги уходят из кошелька сразу, а перебитому
/// возвращаются той же транзакцией. Когда торг кончился, у каждого места одно
/// из двух: резерв взят - выручка делится между продавцом и площадкой; не взят
/// - последняя ставка возвращается хозяину. В обоих случаях аккаунты места
/// закрываются и аренда идёт обратно продавцу.
///
/// Выплата продавцу ждёт пруфа. Срок на пруф продавец ставит при открытии
/// торга. Прислал - у каждого победителя семьдесят два часа оспорить; не
/// оспорил - выплата, оспорил - деньги места заморожены, и решает арбитр (админ
/// настроек): продавцу, победителю или поровну по его доле. Не прислал к сроку
/// - выигравшие ставки возвращаются победителям. Торги, открытые до этого
/// правила (срок пруфа ноль), платят по-старому - сразу после закрытия.
///
/// Шестая стоит в стороне от этого пути: условия площадки - комиссия и тот,
/// кому она идёт, - живут в отдельных настройках, и менять их может только
/// админ. Продавец их не задаёт и не видит в своих параметрах вовсе: торг
/// берёт их сам при открытии. Иначе открывающий аукцион назначал бы комиссию
/// себе, и наши десять процентов держались бы на добросовестности скрипта.
///
/// Деньги у мест раздельные: своё хранилище, свой победитель, своя выплата.
/// Общее у них - время, продавец, комиссия и её получатель.
///
/// Типа места здесь нет и не будет: блокчейну всё равно, аватарка это или бок
/// чемодана. Все различия между поверхностями живут в нашей базе.
#[program]
pub mod oxar_escrow {
    use super::*;

    /// Задать условия площадки: комиссию и кошелёк, куда она идёт.
    ///
    /// Первый вызов заводит настройки, дальше менять их может только админ.
    /// Посылается сразу за выкатом программы. `new_admin` передаёт админство:
    /// пусто - остаётся как есть.
    pub fn admin_sets_terms(
        ctx: Context<AdminSetsTerms>,
        fee_bps: u16,
        new_admin: Option<Pubkey>,
    ) -> Result<()> {
        admin_sets_terms::set_terms(ctx, fee_bps, new_admin)
    }

    /// Продавец открывает торг вещи: срок и продление - на всю вещь.
    ///
    /// Комиссии среди входных данных нет намеренно: её и получателя берём из
    /// настроек площадки, иначе открывающий торг назначал бы их себе.
    pub fn seller_opens_sale(
        ctx: Context<SellerOpensSale>,
        sale_id: [u8; 16],
        closes_at: i64,
        extend_seconds: i64,
        proof_deadline: i64,
    ) -> Result<()> {
        seller_opens_sale::open_sale(ctx, sale_id, closes_at, extend_seconds, proof_deadline)
    }

    /// Продавец открывает место на вещи. Денег в хранилище ещё нет.
    pub fn seller_opens_lot(
        ctx: Context<SellerOpensLot>,
        auction: [u8; 16],
        reserve: u64,
        min_step: u64,
    ) -> Result<()> {
        seller_opens_lot::open_lot(ctx, auction, reserve, min_step)
    }

    /// Ставка: деньги уходят в хранилище, прежнему лидеру возвращаются тут же,
    /// а конец торга всей вещи двигается вперёд, если ставка пришла под конец.
    pub fn bidder_places_bid(ctx: Context<BidderPlacesBid>, amount: u64) -> Result<()> {
        bidder_places_bid::place_bid(ctx, amount)
    }

    /// Место ушло с победителем: выручка продавцу, комиссия площадке.
    pub fn lot_pays_seller(ctx: Context<LotPaysSeller>) -> Result<()> {
        lot_pays_seller::pay_seller(ctx)
    }

    /// Место кончилось ничем: ставка ниже резерва возвращается, аккаунты
    /// закрываются.
    pub fn seller_closes_lot(ctx: Context<SellerClosesLot>) -> Result<()> {
        seller_closes_lot::close_lot(ctx)
    }

    /// Продавец показывает вещь в деле: хеш пруфа - в событие, время - в торг.
    pub fn seller_submits_proof(ctx: Context<SellerSubmitsProof>, proof_hash: [u8; 32]) -> Result<()> {
        seller_submits_proof::submit_proof(ctx, proof_hash)
    }

    /// Победитель оспаривает пруф: деньги места замораживаются до арбитра.
    pub fn winner_disputes(ctx: Context<WinnerDisputes>) -> Result<()> {
        winner_disputes::dispute(ctx)
    }

    /// Арбитр делит ставку оспоренного места между продавцом и победителем.
    pub fn arbiter_decides(ctx: Context<ArbiterDecides>, seller_bps: u16) -> Result<()> {
        arbiter_decides::decide(ctx, seller_bps)
    }
}
