use anchor_lang::prelude::*;
use anchor_spl::token::Mint;

use crate::{error::EscrowError, state::Config};

/// Завести настройки площадки или поменять их.
///
/// Настроек три: комиссия, кошелёк под неё и монета, в которой идут торги.
///
/// Одна инструкция на оба случая, а не две почти одинаковых: `init_if_needed`
/// заводит аккаунт при первом вызове и открывает уже заведённый при следующих.
/// Разница между «первый раз» и «поменяли» здесь только в том, был ли админ
/// раньше, и её достаточно проверить одной строкой.
///
/// Первый вызов делается один раз после выката программы и назначает админом
/// того, кто подписал. Все следующие требуют подписи именно его: чужая
/// транзакция сюда не проходит, и комиссию себе никто не перепишет.
///
/// **Первым может быть только владелец программы.** Адрес программы известен
/// заранее - он вшит в неё, - поэтому между выкатом и первым вызовом есть щель,
/// и бот, следящий за выкатами, успел бы позвать раньше нас. Получив настройки,
/// он поставил бы получателем комиссии себя и сто процентов её размером, а
/// торги, открытые до того, как мы это заметим, вморозили бы его адрес навсегда:
/// получатель в торге по замыслу не меняется.
///
/// Поэтому на первом вызове программа спрашивает не «кто ты», а «твоё ли это».
/// Право на обновление программы - единственное, чего нельзя подделать и что
/// заведомо наше с самого выката. Дальше админ живёт сам по себе: право на
/// обновление можно будет отдать или сжечь, настройки от этого не потеряются.
#[derive(Accounts)]
pub struct AdminSetsTerms<'info> {
    #[account(mut)]
    pub admin: Signer<'info>,

    /// Настройки площадки. Сиды постоянные, поэтому адрес единственный: чужой
    /// счёт на это место не встанет.
    #[account(
        init_if_needed,
        payer = admin,
        space = 8 + Config::INIT_SPACE,
        seeds = [b"config"],
        bump
    )]
    pub config: Account<'info, Config>,

    /// CHECK: владелец счёта, на который пойдёт комиссия. Подписи от него не
    /// требуется - это адрес получателя, а не сторона сделки.
    pub platform: UncheckedAccount<'info>,

    /// Монета торгов - USDC. Берём аккаунтом, а не голым адресом, чтобы
    /// опечатка в адресе отбилась здесь, а не на открытии первого места:
    /// настоящей монетой сюда встанет только настоящая монета.
    /// И только обычной: `Account<Mint>` принимает монеты классической
    /// токен-программы и отвергает Token-2022. Расширения там ломают учёт
    /// по-разному и все одинаково дорого - комиссия за перевод разводит
    /// хранилище со ставкой, постоянный делегат вынимает деньги без подписи,
    /// хук отдаёт третьей стороне рубильник. Проще не пускать их вовсе.
    pub mint: Account<'info, Mint>,

    /// CHECK: служебный аккаунт программы у загрузчика - в нём лежит право на
    /// обновление. Адрес не передаётся на веру, а выводится в обработчике из
    /// адреса самой программы; байты разбираются руками. Готовый тип Anchor
    /// делал бы то же самое через универсальный десериализатор, который тянет
    /// в бинарник заметный кусок кода, - а залог на выкате платится за байты.
    pub program_data: UncheckedAccount<'info>,

    pub system_program: Program<'info, System>,
}

/// У кого право на обновление этой программы.
///
/// Пусто - права нет ни у кого: либо в аккаунте так и записано, либо аккаунт
/// не о том. Строгость здесь не нужна: ответ дальше сверяется с подписью, и
/// «не разобрал» отличается от «хозяина нет» только словами.
fn upgrade_authority(program_data: &UncheckedAccount) -> Option<Pubkey> {
    // Адрес единственный: он выводится из адреса программы, как и любой PDA.
    // Чужой аккаунт на это место не встанет, чей бы он ни был.
    let (expected, _) = Pubkey::find_program_address(
        &[crate::ID.as_ref()],
        &anchor_lang::solana_program::bpf_loader_upgradeable::ID,
    );
    if program_data.key() != expected {
        return None;
    }

    // Раскладка ProgramData у загрузчика: четыре байта вида записи (3 - это
    // programdata), восемь - слот выката, байт «есть ли хозяин», тридцать два
    // - сам хозяин.
    let data = program_data.try_borrow_data().ok()?;
    if data.len() < 45 || data[0] != 3 || data[12] != 1 {
        return None;
    }
    Pubkey::try_from(&data[13..45]).ok()
}

pub fn set_terms(ctx: Context<AdminSetsTerms>, fee_bps: u16) -> Result<()> {
    require!(fee_bps <= 10_000, EscrowError::FeeTooHigh);

    let config = &mut ctx.accounts.config;

    // Пустой админ бывает ровно в одном случае: аккаунт только что заведён
    // этим же вызовом. Тогда админом становится подписавший. Во всех
    // остальных случаях подписать обязан тот, кто уже записан.
    if config.admin == Pubkey::default() {
        // Первый вызов: админом становится тот, у кого право на обновление
        // программы. Никому другому настройки не завести, а значит и щели
        // между выкатом и этим вызовом нет.
        //
        // Права может не быть ни у кого - программу тогда уже заморозили
        // навсегда. Отбирать право умеет только его хозяин, то есть мы, и
        // сделать это раньше первого вызова означало бы выкатить программу,
        // которую нельзя ни настроить, ни починить. Случай бессмысленный, и
        // стеречь его нечем: спрашивать подпись не у кого.
        //
        // Пустым оно бывает двух видов: «нет» и нулевой ключ. Второй кладёт
        // валидатор на прогоне - он поднимает программу сразу замороженной, -
        // и различать их незачем: хозяина нет ни там, ни там.
        let owner = upgrade_authority(&ctx.accounts.program_data).unwrap_or_default();
        if owner != Pubkey::default() {
            require_keys_eq!(owner, ctx.accounts.admin.key(), EscrowError::NotTheAdmin);
        }

        config.admin = ctx.accounts.admin.key();
        config.bump = ctx.bumps.config;
    } else {
        require_keys_eq!(
            config.admin,
            ctx.accounts.admin.key(),
            EscrowError::NotTheAdmin
        );
    }

    config.platform = ctx.accounts.platform.key();
    config.fee_bps = fee_bps;
    config.mint = ctx.accounts.mint.key();

    Ok(())
}
