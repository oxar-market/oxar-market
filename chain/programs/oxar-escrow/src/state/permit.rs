use anchor_lang::prelude::*;

/// Разрешение площадки открыть торг без пруфа.
///
/// Без пруфа деньги победителей уходят продавцу сразу по закрытию, и защиты
/// покупателя у такого торга нет. Поэтому решает не продавец, а админ: он
/// выдаёт разрешение на один торг (адрес выводится из его id) одному
/// продавцу. Тот же торг второй раз не открыть - его адрес занят, - так что
/// разрешение одноразовое само собой. Аренду за него админ забирает отзывом.
#[account]
#[derive(InitSpace)]
pub struct SalePermit {
    /// Кому разрешено: открыть торг по разрешению может только он.
    pub seller: Pubkey,
    pub bump: u8,
}
