use anchor_lang::prelude::*;

/// Настройки площадки: комиссия и тот, кому она идёт.
///
/// Аккаунт один на всю программу - сиды у него постоянные, без чьего-либо
/// адреса внутри. Поэтому он и не может быть подменён: какой бы счёт ни
/// подставили в транзакцию, Anchor выведет тот же единственный адрес и
/// откажется работать с чужим.
///
/// Заведён он ровно затем, чтобы комиссию задавали не те, кто открывает торги.
/// Раньше размер и получателя называл открывающий, и пока торги открывали мы
/// сами, это работало. Но инструкция открытия - общая: стоит продавцам начать
/// заводить аукционы самостоятельно, и они вызовут ту же самую, поставив себе
/// ноль процентов. Наши десять держались бы на честном слове скрипта, а не на
/// правиле программы.
///
/// Условия переезжают в торг при его открытии и дальше не меняются. Это не
/// мелочь: иначе человек, открывший аукцион под десять процентов, однажды
/// обнаружил бы тридцать - и был бы прав, назвав это обманом.
#[account]
#[derive(InitSpace)]
pub struct Config {
    /// Кто вправе менять условия. Больше он не может ничего: ни тронуть
    /// чужие деньги, ни закрыть торг, ни отменить ставку.
    pub admin: Pubkey,

    /// Владелец счёта, на который идёт комиссия со всех торгов.
    pub platform: Pubkey,

    /// Комиссия площадки в сотых долях процента. 1000 - это 10%.
    pub fee_bps: u16,

    pub bump: u8,

    /// Запас под поля, которых ещё нет. Без него добавить поле означает
    /// сломать чтение уже заведённых настроек.
    pub reserved: [u8; 32],
}
