use anchor_lang::prelude::*;

use crate::error::EscrowError;

/// Потолок продления. Час - это уже не «дать людям ответить», а способ
/// растянуть торг бесконечно, подавая по ставке раз в пятьдесят минут.
pub const MAX_EXTEND_SECONDS: i64 = 3_600;

/// Одни торги: деньги участников лежат здесь, а не на честном слове.
///
/// Ставка обеспечена всегда. Пока ставка высшая, её сумма заперта в хранилище
/// лота; как только её перебили, деньги той же транзакцией возвращаются
/// прежнему участнику. Поэтому хранилище на лот одно, а не по одному на
/// каждого: в нём в любой момент лежит ровно текущая высшая ставка.
///
/// Так закрывается дыра, из-за которой можно было выиграть торг суммой,
/// которой у тебя нет: ставка не принимается, если денег не хватило на перевод.
#[account]
#[derive(InitSpace)]
pub struct Lot {
    /// Кто продаёт. Только он открывает торг и получает аренду назад.
    pub seller: Pubkey,
    /// Монета торга. В хранилище может лежать только она.
    pub mint: Pubkey,

    /// Кто сейчас ведёт. Пусто, пока ставок нет.
    pub top_bidder: Option<Pubkey>,
    /// Сколько стоит высшая ставка. Ровно столько лежит в хранилище.
    pub top_bid: u64,

    /// Ниже этого ставки не принимаются вовсе.
    pub reserve: u64,
    /// Наименьшая прибавка к высшей ставке.
    ///
    /// Приходит снаружи, а не считается здесь, потому что «не меньше доллара»
    /// зависит от числа знаков у монеты, а программе про монеты знать нечего.
    pub min_step: u64,

    /// Когда торг закрывается. Ставка под конец двигает это вперёд и никогда
    /// назад.
    pub closes_at: i64,

    /// На сколько секунд ставка под конец отодвигает закрытие.
    ///
    /// Поле, а не константа. Без продления весь аукцион сводится к одной ставке
    /// в последнюю секунду: выигрывает не тот, кто дал больше, а тот, у кого
    /// быстрее интернет. Но сколько именно давать на ответ - свойство торга, а
    /// не программы: недельному лоту пять минут в самый раз, а часовому много.
    pub extend_seconds: i64,

    /// Идентификатор лота из нашей базы, шестнадцать байт uuid. Он же входит в
    /// сиды PDA, поэтому хранить его обязательно: без него лот не может
    /// подписать возврат из собственного хранилища.
    pub auction: [u8; 16],

    /// Комиссия площадки в сотых долях процента. 1000 - это 10%.
    pub fee_bps: u16,

    pub bump: u8,
    pub vault_bump: u8,

    /// Владелец счёта, на который уйдёт комиссия.
    ///
    /// Записывается при открытии торга и дальше не меняется. Это не мелочь:
    /// пока получателя комиссии называл тот, кто двигает торг, он мог назвать
    /// себя - выплату зовёт кто угодно, и десять процентов уходили бы ему.
    ///
    /// Поле стоит в конце, за `vault_bump`, и откусано от запаса, а не
    /// добавлено сверху. Раскладка начала записи от этого не съезжает, и
    /// разбор лота в приложении продолжает читать те же байты на тех же
    /// местах.
    pub platform: Pubkey,

    /// Запас под поля, которых ещё нет. Без него добавить поле означает сломать
    /// чтение уже открытых лотов.
    pub reserved: [u8; 32],
}

impl Lot {
    /// Наименьшая сумма, с которой примут следующую ставку.
    ///
    /// Первая равна резерву. Дальше шаг: пять процентов от текущей высшей, но
    /// не мельче `min_step`. Те же числа лежат в `packages/core` для интерфейса,
    /// и разойтись они не должны: иначе человек увидит один минимум, а контракт
    /// отвергнет ставку по другому.
    pub fn min_next_bid(&self) -> Result<u64> {
        if self.top_bidder.is_none() {
            return Ok(self.reserve);
        }

        let five_percent = self
            .top_bid
            .checked_mul(5)
            .ok_or(EscrowError::MathOverflow)?
            / 100;
        let step = five_percent.max(self.min_step);

        self.top_bid
            .checked_add(step)
            .ok_or(EscrowError::MathOverflow.into())
    }

    /// Идёт ли торг прямо сейчас.
    pub fn is_open(&self, now: i64) -> bool {
        now < self.closes_at
    }

    /// Состоялся ли торг: есть ставка, и она не ниже резерва.
    ///
    /// Резерв проверяется и здесь, хотя ставку ниже него не принимают на входе.
    /// Это не лишняя проверка, а страховка на случай, если правило приёма
    /// когда-нибудь изменят: победитель ниже резерва не должен появиться ни при
    /// каких правках.
    pub fn has_winner(&self) -> bool {
        self.top_bidder.is_some() && self.top_bid >= self.reserve
    }

    /// Как делится выигравшая ставка: комиссия площадке, остальное продавцу.
    ///
    /// Комиссия считается вниз, остаток от деления достаётся продавцу. Сумма
    /// двух частей равна исходной всегда - в хранилище не должно оставаться ни
    /// одной базовой единицы, иначе его не закрыть.
    pub fn split(&self, payout: u64) -> Result<(u64, u64)> {
        let fee = (payout as u128)
            .checked_mul(self.fee_bps as u128)
            .and_then(|v| v.checked_div(10_000))
            .ok_or(EscrowError::MathOverflow)? as u64;

        let to_seller = payout.checked_sub(fee).ok_or(EscrowError::MathOverflow)?;

        Ok((fee, to_seller))
    }

    /// Куда отодвинуть закрытие, если ставка пришла под конец.
    ///
    /// Возвращает новое время закрытия или прежнее, если двигать не нужно.
    /// Уменьшить срок этим нельзя ни при каких входных данных.
    pub fn extended(&self, now: i64) -> i64 {
        let left = self.closes_at.saturating_sub(now);
        if left < self.extend_seconds {
            now.saturating_add(self.extend_seconds)
        } else {
            self.closes_at
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Торг с комиссией в 10% и высшей ставкой, которую и делим.
    fn lot(fee_bps: u16, top_bid: u64) -> Lot {
        Lot {
            seller: Pubkey::default(),
            mint: Pubkey::default(),
            top_bidder: Some(Pubkey::default()),
            top_bid,
            reserve: 1,
            min_step: 1,
            closes_at: 0,
            extend_seconds: 0,
            auction: [0u8; 16],
            fee_bps,
            bump: 0,
            vault_bump: 0,
            platform: Pubkey::default(),
            reserved: [0u8; 32],
        }
    }

    #[test]
    fn комиссия_десять_процентов_и_ничего_не_теряется() {
        let (fee, to_seller) = lot(1_000, 100).split(100).unwrap();
        assert_eq!(fee, 10);
        assert_eq!(to_seller, 90);
        assert_eq!(fee + to_seller, 100, "в хранилище не должно остаться ничего");
    }

    #[test]
    fn нулевая_комиссия_отдаёт_всё_продавцу() {
        let (fee, to_seller) = lot(0, 100).split(100).unwrap();
        assert_eq!(fee, 0);
        assert_eq!(to_seller, 100);
    }

    #[test]
    fn остаток_от_деления_достаётся_продавцу_а_не_виснет() {
        // 10% от 105 это 10.5 базовой единицы. Комиссия вниз, половинка
        // продавцу: иначе она осталась бы в хранилище и закрыть его не вышло бы.
        let (fee, to_seller) = lot(1_000, 105).split(105).unwrap();
        assert_eq!(fee, 10);
        assert_eq!(to_seller, 95);
        assert_eq!(fee + to_seller, 105);
    }

    #[test]
    fn комиссия_во_все_сто_процентов_не_уводит_продавца_в_минус() {
        let (fee, to_seller) = lot(10_000, 100).split(100).unwrap();
        assert_eq!(fee, 100);
        assert_eq!(to_seller, 0);
    }

    #[test]
    fn большая_ставка_не_переполняет_счёт() {
        // Промежуточное умножение на 10 000 не влезает в u64, поэтому считается
        // в u128. Без этого комиссия с крупной ставки обернулась бы мусором.
        let (fee, to_seller) = lot(1_000, u64::MAX).split(u64::MAX).unwrap();
        assert_eq!(fee, u64::MAX / 10);
        assert_eq!(fee as u128 + to_seller as u128, u64::MAX as u128);
    }

    #[test]
    fn торг_состоялся_только_если_ставка_не_ниже_резерва() {
        let mut one = lot(1_000, 40);
        one.reserve = 50;
        assert!(!one.has_winner(), "ставка ниже резерва - лот не продан");

        one.top_bid = 50;
        assert!(one.has_winner(), "ровно резерв уже победа");

        one.top_bidder = None;
        assert!(!one.has_winner(), "без ставок победителя нет");
    }
}
