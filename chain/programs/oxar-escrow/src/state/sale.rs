use anchor_lang::prelude::*;

/// Потолок продления. Час - это уже не «дать людям ответить», а способ
/// растянуть торг бесконечно, подавая по ставке раз в пятьдесят минут.
pub const MAX_EXTEND_SECONDS: i64 = 3_600;

/// На сколько ставки суммарно могут отодвинуть конец торга. Час.
///
/// Продление - это финальная перестрелка, и она не зависит от того, шёл торг
/// три дня или неделю: спорят последние двое, а не календарь. Час - это
/// двенадцать раундов по пять минут, и каждый раунд поднимает цену минимум на
/// пять процентов: не решили за час - цена уже почти удвоилась, и торг честно
/// заканчивается на том, кто дал больше.
///
/// Без потолка два кошелька, перебивая друг друга по доллару на самом дешёвом
/// месте, держали бы открытой всю вещь бесконечно: продавец не получает вещь,
/// победители дорогих мест не могут закрыться.
pub const TOTAL_EXTEND_SECONDS: i64 = 3_600;

/// Потолок всего торга - тридцать дней.
///
/// Срок задаёт тот, кто открывает, и до сих пор он мог поставить любой: хоть
/// две тысячи сотый год. Отменить торг нечем, участник свою ставку забрать не
/// может, пока его не перебьют, - значит опечатка в одну цифру запирала бы
/// чужие деньги на срок, которого никто не переживёт. Месяц заведомо больше
/// любого разумного аукциона за место на футболке и заведомо меньше беды.
pub const MAX_SALE_SECONDS: i64 = 30 * 24 * 60 * 60;

/// Торг вещи целиком.
///
/// Продаётся не место по отдельности, а вся футболка разом: пятнадцать мест
/// живут одним торгом и закрываются в одну и ту же секунду. Значит срок - это
/// свойство вещи, а не места, и лежит он здесь, а не в каждом лоте. Иначе
/// места неизбежно разъезжаются: открытые на секунду позже закрываются на
/// секунду позже, а ставка под конец продлевала бы только своё место.
///
/// Ставка на любое место двигает конец всей вещи. Так и работает торг вживую:
/// перебил кто-то грудь в последнюю секунду - время добавляется всем, потому
/// что борьба идёт за одну футболку.
///
/// Деньги сюда не заходят: у каждого места своё хранилище, свой победитель и
/// своя выплата. Общее здесь - время, продавец, комиссия и её получатель.
#[account]
#[derive(InitSpace)]
pub struct Sale {
    /// Идентификатор торга из нашей базы, шестнадцать байт uuid. Он же входит
    /// в сиды PDA, поэтому хранить его обязательно.
    pub sale: [u8; 16],

    /// Кто продаёт вещь. Один на все её места: футболка одна.
    pub seller: Pubkey,
    /// Куда идёт комиссия со всех мест. Записывается при открытии торга и
    /// дальше не меняется: иначе тот, кто зовёт выплату, назначил бы
    /// получателем себя.
    pub platform: Pubkey,

    /// Когда торг закрывается - весь, со всеми местами. Ставка под конец
    /// двигает это вперёд и никогда назад.
    pub closes_at: i64,

    /// На сколько секунд ставка под конец отодвигает закрытие всей вещи.
    ///
    /// Поле, а не константа: недельному торгу пять минут в самый раз, а
    /// часовому много.
    pub extend_seconds: i64,

    /// Комиссия площадки в сотых долях процента. 1000 - это 10%. Одна на все
    /// места: торг один.
    pub fee_bps: u16,

    pub bump: u8,

    /// Дальше этого не продлить: заявленный при открытии конец плюс час.
    /// Ставки двигают `closes_at` вперёд, но только до сюда.
    ///
    /// Поле легло на первые восемь байт прежнего запаса, поэтому уже открытые
    /// торги читаются по-старому, а потолок в них оказывается нулевым. Ноль -
    /// это «потолка нет»: так они дорабатывают по правилам, по которым
    /// открывались, а укоротить чей-то идущий торг задним числом нельзя.
    pub hard_closes_at: i64,

    /// Запас под поля, которых ещё нет. Без него добавить поле означает
    /// сломать чтение уже открытых торгов.
    pub reserved: [u8; 24],
}

impl Sale {
    /// Идёт ли торг прямо сейчас. Один ответ на все места вещи.
    pub fn is_open(&self, now: i64) -> bool {
        now < self.closes_at
    }

    /// Куда отодвинуть закрытие, если ставка пришла под конец.
    ///
    /// Возвращает новое время закрытия или прежнее, если двигать не нужно.
    /// Уменьшить срок этим нельзя ни при каких входных данных: новое время не
    /// бывает меньше старого, а жёсткий конец не бывает раньше текущего срока
    /// - `closes_at` растёт только до него.
    pub fn extended(&self, now: i64) -> i64 {
        let left = self.closes_at.saturating_sub(now);
        if left >= self.extend_seconds {
            return self.closes_at;
        }

        let moved = now.saturating_add(self.extend_seconds);
        // Ноль - торг открыт до появления потолка и дорабатывает без него.
        if self.hard_closes_at == 0 {
            moved
        } else {
            moved.min(self.hard_closes_at).max(self.closes_at)
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sale(closes_at: i64, extend_seconds: i64) -> Sale {
        Sale {
            sale: [0u8; 16],
            seller: Pubkey::default(),
            platform: Pubkey::default(),
            closes_at,
            extend_seconds,
            fee_bps: 1000,
            bump: 0,
            hard_closes_at: closes_at + TOTAL_EXTEND_SECONDS,
            reserved: [0u8; 24],
        }
    }

    #[test]
    fn торг_идёт_пока_не_вышел_срок() {
        let one = sale(100, 30);
        assert!(one.is_open(99), "до срока торг идёт");
        assert!(!one.is_open(100), "в саму секунду закрытия уже нет");
        assert!(!one.is_open(101), "после срока тем более");
    }

    #[test]
    fn ставка_под_конец_двигает_срок_всей_вещи() {
        let one = sale(100, 30);
        // До конца 10 секунд, окно продления 30 - двигаем от самой ставки.
        assert_eq!(one.extended(90), 120, "продление считается от ставки");
    }

    #[test]
    fn ставка_заранее_срок_не_трогает() {
        let one = sale(100, 30);
        // До конца 40 секунд, окно 30 - двигать нечего.
        assert_eq!(one.extended(60), 100, "вне окна срок прежний");
    }

    #[test]
    fn продление_никогда_не_укорачивает_торг() {
        let one = sale(100, 30);
        // Ставка в самую последнюю секунду: срок обязан вырасти, а не упасть.
        assert_eq!(one.extended(99), 129, "срок только вперёд");
        // И даже ставка после закрытия не может утащить срок назад - такую
        // ставку не примут, но арифметика обязана быть безопасной сама по себе.
        assert!(one.extended(200) >= one.closes_at, "назад срок не идёт");
    }

    #[test]
    fn перестрелка_не_тянет_торг_дальше_жёсткого_конца() {
        // Ставка за секунду до конца, каждый раз заново - так выглядела бы
        // пара кошельков, перебивающих друг друга по доллару.
        let mut one = sale(100, 30);
        for _ in 0..1_000 {
            let now = one.closes_at - 1;
            one.closes_at = one.extended(now);
        }
        assert_eq!(
            one.closes_at, one.hard_closes_at,
            "тысяча ставок упёрлась не в потолок"
        );
    }

    #[test]
    fn продление_у_потолка_даёт_сколько_осталось_а_не_ничего() {
        let mut one = sale(100, 30);
        one.hard_closes_at = 110;
        // До потолка десять секунд: продлеваем на них, а не на полные тридцать
        // и не на ноль.
        assert_eq!(one.extended(99), 110, "продление обязано упереться в потолок");
        // И даже у самого потолка срок не идёт назад.
        one.closes_at = 110;
        assert!(one.extended(109) >= 110, "у потолка срок утащило назад");
    }

    #[test]
    fn торг_без_потолка_дорабатывает_по_старым_правилам() {
        // Ноль в поле - торг открыт до появления потолка: читается из старого
        // аккаунта, где на этом месте лежал запас.
        let mut one = sale(100, 30);
        one.hard_closes_at = 0;
        assert_eq!(one.extended(99), 129, "старый торг продлился не как раньше");
    }
}
