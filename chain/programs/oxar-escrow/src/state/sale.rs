use anchor_lang::prelude::*;

/// Потолок продления. Час - это уже не «дать людям ответить», а способ
/// растянуть торг бесконечно, подавая по ставке раз в пятьдесят минут.
pub const MAX_EXTEND_SECONDS: i64 = 3_600;

/// На сколько ставки суммарно могут отодвинуть конец торга. Час.
///
/// Продление - это финальная перестрелка, и она не зависит от того, шёл торг
/// три дня или неделю: спорят последние двое, а не календарь. Час - это
/// двенадцать раундов по пять минут, и каждый раунд поднимает цену минимум на
/// пять процентов: не решили за час - цена уже почти удвоилась, и торг честно
/// заканчивается на том, кто дал больше.
///
/// Без потолка два кошелька, перебивая друг друга по доллару на самом дешёвом
/// месте, держали бы открытой всю вещь бесконечно: продавец не получает вещь,
/// победители дорогих мест не могут закрыться.
pub const TOTAL_EXTEND_SECONDS: i64 = 3_600;

/// Потолок всего торга - тридцать дней.
///
/// Срок задаёт тот, кто открывает, и до сих пор он мог поставить любой: хоть
/// две тысячи сотый год. Отменить торг нечем, участник свою ставку забрать не
/// может, пока его не перебьют, - значит опечатка в одну цифру запирала бы
/// чужие деньги на срок, которого никто не переживёт. Месяц заведомо больше
/// любого разумного аукциона за место на футболке и заведомо меньше беды.
pub const MAX_SALE_SECONDS: i64 = 30 * 24 * 60 * 60;

/// Сколько у победителя есть, чтобы оспорить пруф. Семьдесят два часа.
///
/// Пруф присылает продавец, и деньги до него держит программа. Но пруф может
/// быть не тем: не та вещь, не тот логотип, фото из прошлого года. Поэтому
/// после пруфа у победителя трое суток на «нет»; промолчал - выплата.
/// Подтвердил сам - выплата сразу, ждать незачем.
pub const APPEAL_SECONDS: i64 = 72 * 60 * 60;

/// Насколько арбитр может отодвинуть срок пруфа от того, под который ставили.
/// Девяносто дней - ивент переносят на недели, а не на годы. Потолок от
/// первого срока, а не от текущего: переносы по частям его не обойдут.
pub const MAX_PROOF_MOVE_SECONDS: i64 = 90 * 24 * 60 * 60;

/// Торг вещи целиком.
///
/// Продаётся не место по отдельности, а вся футболка разом: пятнадцать мест
/// живут одним торгом и закрываются в одну и ту же секунду. Значит срок - это
/// свойство вещи, а не места, и лежит он здесь, а не в каждом лоте. Иначе
/// места неизбежно разъезжаются: открытые на секунду позже закрываются на
/// секунду позже, а ставка под конец продлевала бы только своё место.
///
/// Ставка на любое место двигает конец всей вещи. Так и работает торг вживую:
/// перебил кто-то грудь в последнюю секунду - время добавляется всем, потому
/// что борьба идёт за одну футболку.
///
/// Деньги сюда не заходят: у каждого места своё хранилище, свой победитель и
/// своя выплата. Общее здесь - время, продавец, комиссия и её получатель.
#[account]
#[derive(InitSpace)]
pub struct Sale {
    /// Идентификатор торга из нашей базы, шестнадцать байт uuid. Он же входит
    /// в сиды PDA, поэтому хранить его обязательно.
    pub sale: [u8; 16],

    /// Кто продаёт вещь. Один на все её места: футболка одна.
    pub seller: Pubkey,
    /// Куда идёт комиссия со всех мест. Записывается при открытии торга и
    /// дальше не меняется: иначе тот, кто зовёт выплату, назначил бы
    /// получателем себя.
    pub platform: Pubkey,

    /// Когда торг закрывается - весь, со всеми местами. Ставка под конец
    /// двигает это вперёд и никогда назад.
    pub closes_at: i64,

    /// На сколько секунд ставка под конец отодвигает закрытие всей вещи.
    ///
    /// Поле, а не константа: недельному торгу пять минут в самый раз, а
    /// часовому много.
    pub extend_seconds: i64,

    /// Комиссия площадки в сотых долях процента. 1000 - это 10%. Одна на все
    /// места: торг один.
    pub fee_bps: u16,

    pub bump: u8,

    /// Дальше этого не продлить: заявленный при открытии конец плюс час.
    /// Ставки двигают `closes_at` вперёд, но только до сюда.
    ///
    /// Поле легло на первые восемь байт прежнего запаса, поэтому уже открытые
    /// торги читаются по-старому, а потолок в них оказывается нулевым. Ноль -
    /// это «потолка нет»: так они дорабатывают по правилам, по которым
    /// открывались, а укоротить чей-то идущий торг задним числом нельзя.
    pub hard_closes_at: i64,

    /// До когда продавец обязан прислать пруф - фото или ссылку на вещь в деле.
    /// Ставит продавец при открытии, видно до ставки, дальше не меняется.
    /// Верхней границы нет: ивент бывает и через полгода, и ждать денег до
    /// него - выбор продавца.
    ///
    /// Не прислал к сроку - победители получают ставки обратно. Ноль - торг
    /// открыт до защиты покупателя (на этом месте лежал запас) и платит по
    /// старым правилам: сразу после закрытия.
    pub proof_deadline: i64,

    /// Когда пруф пришёл. Ноль - ещё нет. Сам пруф лежит у нас, а его хеш
    /// ушёл событием в транзакцию: в запас аккаунта он не помещается.
    pub proved_at: i64,

    /// Срок пруфа, под который ставили, - при открытии торга. От него
    /// считается потолок переносов. Лёг на последние байты прежнего запаса.
    pub first_proof_deadline: i64,
}

impl Sale {
    /// Идёт ли торг прямо сейчас. Один ответ на все места вещи.
    pub fn is_open(&self, now: i64) -> bool {
        now < self.closes_at
    }

    /// Куда отодвинуть закрытие, если ставка пришла под конец.
    ///
    /// Возвращает новое время закрытия или прежнее, если двигать не нужно.
    /// Уменьшить срок этим нельзя ни при каких входных данных: новое время не
    /// бывает меньше старого, а жёсткий конец не бывает раньше текущего срока
    /// - `closes_at` растёт только до него.
    pub fn extended(&self, now: i64) -> i64 {
        let left = self.closes_at.saturating_sub(now);
        if left >= self.extend_seconds {
            return self.closes_at;
        }

        let moved = now.saturating_add(self.extend_seconds);
        // Ноль - торг открыт до появления потолка и дорабатывает без него.
        if self.hard_closes_at == 0 {
            moved
        } else {
            moved.min(self.hard_closes_at).max(self.closes_at)
        }
    }

    /// Торг открыт до защиты покупателя и дорабатывает по старым правилам.
    pub fn legacy(&self) -> bool {
        self.proof_deadline == 0
    }

    /// Принимает ли торг пруф сейчас: торг закрылся, срок не вышел, пруфа
    /// ещё не было.
    pub fn takes_proof(&self, now: i64) -> bool {
        !self.legacy() && self.proved_at == 0 && !self.is_open(now) && now <= self.proof_deadline
    }

    /// Срок вышел, а пруфа нет: деньги победителей возвращаются им.
    pub fn proof_missed(&self, now: i64) -> bool {
        !self.legacy() && self.proved_at == 0 && !self.is_open(now) && now > self.proof_deadline
    }

    /// Можно ли арбитру перенести срок пруфа на `new_deadline`: только позже,
    /// не дальше девяноста дней от первого срока, только пока пруфа нет и
    /// срок не вышел. Вышедший срок уже дал
    /// победителям право на возврат - отнимать его переносом нельзя.
    pub fn moves_proof(&self, now: i64, new_deadline: i64) -> bool {
        !self.legacy()
            && self.proved_at == 0
            && now <= self.proof_deadline
            && new_deadline > self.proof_deadline
            && new_deadline <= self.first_proof_deadline.saturating_add(MAX_PROOF_MOVE_SECONDS)
    }

    /// Можно ли сейчас оспорить пруф.
    pub fn appeal_open(&self, now: i64) -> bool {
        !self.legacy() && self.proved_at > 0 && now < self.proved_at.saturating_add(APPEAL_SECONDS)
    }

    /// Можно ли платить продавцу. `by_winner` - выплату зовёт сам победитель
    /// места: это его «да», и окно спора ему ждать незачем.
    ///
    /// Окно и выплата посторонним не пересекаются ни в одну секунду: спор
    /// открыт строго до `proved_at + APPEAL_SECONDS`, выплата - с неё.
    pub fn pays(&self, now: i64, by_winner: bool) -> bool {
        if self.legacy() {
            return !self.is_open(now);
        }
        self.proved_at > 0 && (by_winner || now >= self.proved_at.saturating_add(APPEAL_SECONDS))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sale(closes_at: i64, extend_seconds: i64) -> Sale {
        Sale {
            sale: [0u8; 16],
            seller: Pubkey::default(),
            platform: Pubkey::default(),
            closes_at,
            extend_seconds,
            fee_bps: 1000,
            bump: 0,
            hard_closes_at: closes_at + TOTAL_EXTEND_SECONDS,
            proof_deadline: closes_at + 1_000,
            proved_at: 0,
            first_proof_deadline: closes_at + 1_000,
        }
    }

    #[test]
    fn торг_идёт_пока_не_вышел_срок() {
        let one = sale(100, 30);
        assert!(one.is_open(99), "до срока торг идёт");
        assert!(!one.is_open(100), "в саму секунду закрытия уже нет");
        assert!(!one.is_open(101), "после срока тем более");
    }

    #[test]
    fn ставка_под_конец_двигает_срок_всей_вещи() {
        let one = sale(100, 30);
        // До конца 10 секунд, окно продления 30 - двигаем от самой ставки.
        assert_eq!(one.extended(90), 120, "продление считается от ставки");
    }

    #[test]
    fn ставка_заранее_срок_не_трогает() {
        let one = sale(100, 30);
        // До конца 40 секунд, окно 30 - двигать нечего.
        assert_eq!(one.extended(60), 100, "вне окна срок прежний");
    }

    #[test]
    fn продление_никогда_не_укорачивает_торг() {
        let one = sale(100, 30);
        // Ставка в самую последнюю секунду: срок обязан вырасти, а не упасть.
        assert_eq!(one.extended(99), 129, "срок только вперёд");
        // И даже ставка после закрытия не может утащить срок назад - такую
        // ставку не примут, но арифметика обязана быть безопасной сама по себе.
        assert!(one.extended(200) >= one.closes_at, "назад срок не идёт");
    }

    #[test]
    fn перестрелка_не_тянет_торг_дальше_жёсткого_конца() {
        // Ставка за секунду до конца, каждый раз заново - так выглядела бы
        // пара кошельков, перебивающих друг друга по доллару.
        let mut one = sale(100, 30);
        for _ in 0..1_000 {
            let now = one.closes_at - 1;
            one.closes_at = one.extended(now);
        }
        assert_eq!(
            one.closes_at, one.hard_closes_at,
            "тысяча ставок упёрлась не в потолок"
        );
    }

    #[test]
    fn продление_у_потолка_даёт_сколько_осталось_а_не_ничего() {
        let mut one = sale(100, 30);
        one.hard_closes_at = 110;
        // До потолка десять секунд: продлеваем на них, а не на полные тридцать
        // и не на ноль.
        assert_eq!(one.extended(99), 110, "продление обязано упереться в потолок");
        // И даже у самого потолка срок не идёт назад.
        one.closes_at = 110;
        assert!(one.extended(109) >= 110, "у потолка срок утащило назад");
    }

    #[test]
    fn торг_без_потолка_дорабатывает_по_старым_правилам() {
        // Ноль в поле - торг открыт до появления потолка: читается из старого
        // аккаунта, где на этом месте лежал запас.
        let mut one = sale(100, 30);
        one.hard_closes_at = 0;
        assert_eq!(one.extended(99), 129, "старый торг продлился не как раньше");
    }

    #[test]
    fn пруф_принимается_только_между_закрытием_и_сроком() {
        let one = sale(100, 30);
        assert!(!one.takes_proof(99), "пока идёт торг, печатать ещё нечего");
        assert!(one.takes_proof(100), "торг закрылся - пруф можно");
        assert!(one.takes_proof(1_100), "в саму секунду срока ещё можно");
        assert!(!one.takes_proof(1_101), "после срока поздно");

        let mut proved = sale(100, 30);
        proved.proved_at = 500;
        assert!(!proved.takes_proof(600), "пруф присылают один раз");
    }

    #[test]
    fn нет_пруфа_к_сроку_значит_возврат_победителю() {
        let one = sale(100, 30);
        assert!(!one.proof_missed(1_100), "в секунду срока ещё не опоздал");
        assert!(one.proof_missed(1_101), "срок прошёл без пруфа");

        let mut proved = sale(100, 30);
        proved.proved_at = 500;
        assert!(!proved.proof_missed(5_000), "пруф прислан - возврата нет");
    }

    #[test]
    fn оспорить_можно_семьдесят_два_часа_после_пруфа_и_ни_секундой_дольше() {
        let mut one = sale(100, 30);
        assert!(!one.appeal_open(200), "без пруфа оспаривать нечего");

        one.proved_at = 500;
        assert!(one.appeal_open(500), "сразу после пруфа можно");
        assert!(one.appeal_open(500 + APPEAL_SECONDS - 1), "в последнюю секунду ещё можно");
        assert!(!one.appeal_open(500 + APPEAL_SECONDS), "окно закрылось");
    }

    #[test]
    fn выплата_после_окна_любому_а_до_окна_только_по_слову_победителя() {
        let mut one = sale(100, 30);
        assert!(!one.pays(5_000, true), "без пруфа не платим даже по слову победителя");

        one.proved_at = 500;
        assert!(!one.pays(500 + APPEAL_SECONDS - 1, false), "пока идёт окно, посторонний не выплатит");
        assert!(one.pays(500 + APPEAL_SECONDS - 1, true), "победитель подтвердил - платим сразу");
        assert!(one.pays(500 + APPEAL_SECONDS, false), "окно прошло - выплату зовёт кто угодно");
    }

    #[test]
    fn спор_и_выплата_не_пересекаются_ни_в_одну_секунду() {
        // Иначе выплата и спор в одной секунде гонялись бы за одни деньги.
        let mut one = sale(100, 30);
        one.proved_at = 500;
        for now in 500..(500 + APPEAL_SECONDS + 10) {
            assert!(
                !(one.appeal_open(now) && one.pays(now, false)),
                "в секунду {now} открыты и спор, и выплата"
            );
        }
    }

    #[test]
    fn торг_до_обновления_платит_по_старым_правилам() {
        // Ноль в сроке пруфа - торг открыт до защиты покупателя: в старом
        // аккаунте здесь лежал запас. Он платит сразу и в возврат не уходит,
        // иначе обновление отобрало бы деньги у продавцов, уже продавших места.
        let mut one = sale(100, 30);
        one.proof_deadline = 0;
        assert!(one.pays(100, false), "старый торг ждёт пруфа");
        assert!(!one.proof_missed(10_000_000), "старый торг ушёл в возврат");
        assert!(!one.appeal_open(150), "старый торг можно оспорить");
        assert!(!one.takes_proof(150), "старый торг принимает пруф");
    }

    #[test]
    fn срок_пруфа_арбитр_только_отодвигает_и_только_пока_он_не_вышел() {
        // Ивент перенесли - срок пруфа уезжает вместе с ним.
        let one = sale(100, 30);
        assert!(one.moves_proof(500, 5_000), "отодвинуть до срока можно");
        assert!(one.moves_proof(1_100, 5_000), "в саму секунду срока ещё можно");
        assert!(!one.moves_proof(500, 1_100), "тот же срок - не перенос");
        assert!(!one.moves_proof(500, 900), "раньше срок не двигается: победители на него рассчитывали");
        assert!(!one.moves_proof(1_101, 5_000), "срок вышел - победителям уже положен возврат");

        let mut proved = sale(100, 30);
        proved.proved_at = 500;
        assert!(!proved.moves_proof(600, 5_000), "пруф уже пришёл - двигать нечего");

        let mut legacy = sale(100, 30);
        legacy.proof_deadline = 0;
        assert!(!legacy.moves_proof(50, 5_000), "у старого торга срока пруфа нет");
    }

    #[test]
    fn перенос_срока_не_дальше_девяноста_дней_от_первого() {
        // Срок, под который ставили, плюс девяносто дней - и всё. Иначе арбитр
        // (или украденный ключ) держал бы деньги победителей сколько угодно.
        let mut one = sale(100, 30);
        let first = one.proof_deadline;
        assert!(one.moves_proof(500, first + MAX_PROOF_MOVE_SECONDS), "ровно девяносто дней можно");
        assert!(!one.moves_proof(500, first + MAX_PROOF_MOVE_SECONDS + 1), "дальше - нет");
        // Несколько переносов подряд не складываются: потолок от первого срока.
        one.proof_deadline = first + 60 * 24 * 60 * 60;
        assert!(!one.moves_proof(500, first + MAX_PROOF_MOVE_SECONDS + 1), "переносы по частям обошли потолок");
        assert!(!one.moves_proof(500, i64::MAX), "срок на бесконечность");
    }
}
