import type { Shape, Spot } from "./spots.ts";

/**
 * Чемодан: пять мест на лицевой грани.
 *
 * Модель - Даниила, прислана 29.09.2026 (13 МБ, 87 тысяч граней, свои
 * текстуры); ужата gltf-transform: упрощение до четверти граней, текстуры
 * 1024 px в webp, meshopt - 431 КБ. Прежняя модель (J-Toastie, CC BY 3.0)
 * заменена ею, и подпись автора со страницы Terms снята вместе с ней.
 *
 * Раскладка та же, что была на прежнем чемодане: широкая панель наверху
 * лицевой грани и под ней две пары. Числа сняты с новой модели лучами, как их
 * пускает сцена, а доли грани перенесены с прежней:
 *
 * Лицевая грань - азимут -90. Ручка сдвинута к +X, значит там спина; грань
 * -X к тому же ровнее (нормаль 1.00 против 0.96).
 *
 * Плоская полоса по высоте - от 0.10 до 0.62 габарита (габарит - с ручкой).
 * Прежние высоты 0.65 / 0.47 / 0.31 на полосе 0.20-0.75 переходят в
 * 0.53 / 0.36 / 0.20.
 *
 * По ширине корпус рёбрами: они идут около -50, -65, -100 и -115 градусов.
 * Пары стоят на ровных колонках -60 и -120 - тех же углах, что на прежнем
 * чемодане, только с другой стороны. Лицом к грани -X левый край зрителя -
 * это отрицательный Z, поэтому «left» - -120.
 *
 * Грань уже прежней (0.174 против 0.244 в единицах сцены), и места
 * уменьшены в той же доле, 0.71, чтобы лечь на неё так же.
 */

/** Место под логотип: пара таких стоит в ряд, между ними остаётся просвет. */
const BADGE: [number, number] = [0.068, 0.043];
const LEFT = -120;
const RIGHT = -60;

export const SUITCASE_SPOTS: Spot[] = [
  // Главное место - широкая полоса наверху лицевой грани: чемодан катят перед
  // собой, и смотрят именно сюда.
  { code: "suitcase_panel", label: "Main panel", height: 0.53, azimuth: -90, size: [0.143, 0.075] },
  // Под ней две пары. Левый и правый - со стороны зрителя, не вещи.
  { code: "suitcase_upper_left", label: "Upper left", height: 0.36, azimuth: LEFT, size: BADGE },
  { code: "suitcase_upper_right", label: "Upper right", height: 0.36, azimuth: RIGHT, size: BADGE },
  { code: "suitcase_lower_left", label: "Lower left", height: 0.2, azimuth: LEFT, size: BADGE },
  { code: "suitcase_lower_right", label: "Lower right", height: 0.2, azimuth: RIGHT, size: BADGE },
];

export const SUITCASE: Shape = {
  model: "/models/suitcase.glb",
  spots: SUITCASE_SPOTS,
  // Грани сходятся под прямым углом: глубокая коробка захватила бы соседнюю
  // грань, и пятно завернулось бы за угол.
  depth: 0.05,
  cloth: false,
  noun: "suitcase",
};
