/**
 * Разметка футболки: где на ней лежат места под нанесение.
 *
 * Девять мест сеткой на переде, три на три, пронумерованы слева направо и
 * сверху вниз. Спина пустая намеренно: печать будет только спереди, и
 * рисовать сзади рамки значило бы обещать то, чего не напечатают.
 *
 * Рядов было пять - осталось три: пятнадцать мест на одной груди читались
 * мелкой клеткой, а торг размазывался по местам, которых никто не выбирал.
 * Высоты рядов - вторая, третья и четвёртая из прежней сетки: сетка собрана
 * к центру груди, а числа уже сняты с модели и проверены, изобретать новые
 * незачем.
 *
 * Числа сняты с самой модели лучами, а не подобраны на глаз. Луч летит
 * горизонтально из точки на заданном угле к оси, поэтому перёд футболки для
 * него - почти плоскость: на высотах 0.42-0.70 точка касания стоит на
 * z = 0.122-0.128 и нормаль смотрит на зрителя (nz от 0.94 до 1.00). Отсюда
 * два предела сетки.
 *
 * Снизу - 0.42. Ниже ткань уходит раструбом и нормаль заваливается: на 0.34
 * под углом 24 градуса она даёт уже 0.75, и рамка встаёт косо.
 *
 * Сверху - 0.70. Выше начинается плечо, перёд уходит назад (z падает с 0.122
 * на 0.109 к 0.76 и на 0.092 к 0.82), и верхний ряд перегнуло бы через плечо.
 *
 * По ширине - 21 градус на колонку. На этом угле точка стоит на x = 0.048, а
 * нормаль ещё честная; дальше 32 градусов начинается бок, и там нормаль
 * рушится до 0.68.
 *
 * Коды обязаны совпадать с каталогом в базе (миграция tee_grid) - это
 * проверяет тест рядом.
 */

export type Spot = {
  /** Тот же код, что в thing_spots. По нему место на вещи находит свой лот. */
  code: string;
  label: string;
  /** Высота на вещи: 0 - низ габарита, 1 - верх. */
  height: number;
  /**
   * Угол вокруг оси: 0 - к зрителю, 90 - вправо.
   *
   * Луч летит горизонтально из точки на этом угле к оси, поэтому точка
   * попадания лежит на той же прямой. На плоской грани это даёт сдвиг вдоль
   * неё: колонку сетки можно задать углом, не заводя третью координату.
   */
  azimuth: number;
  /**
   * Сдвиг луча вбок вдоль грани, в единицах сцены; плюс - вправо от зрителя.
   *
   * Нужен тонкой вещи: крышка ноутбука в сантиметре от оси, и сдвинуть место
   * на треть ширины углом можно только под 87 градусов. Такой угол сцена
   * читает как бок и разворачивает вещь к нему.
   */
  shift?: number;
  /**
   * Место сверху: луч падает вниз, а не летит горизонтально. Так ложатся
   * крыша и капот - горизонтальный луч до них не достаёт. `shift` тогда -
   * сдвиг вдоль вещи (плюс - к переду, +X), `height` не читается. Логотип
   * читается спереди вещи, верхом к её корме: размер - поперёк вещи и вдоль.
   */
  top?: boolean;
  /**
   * Узор, а не одна картинка: логотип повторяется рядами со сдвигом через
   * ряд, как значки на галстуке. Так продаётся вещь целиком одному бренду.
   */
  tile?: boolean;
  /**
   * Оклейка: место - панель целиком. Картинка покрывает его от края до края,
   * лишнее по краям срезается, как у печати на капоте; рамка - по самому
   * краю, без полей; пустое место залито, чтобы вещь читалась сеткой зон.
   */
  wrap?: boolean;
  /**
   * Детали модели под этим местом - начала имён их мешей. Пусто - любые.
   * Место на двери ложится только на дверь: печать идёт ровно по её контуру,
   * а край прямоугольника может заходить на соседние детали.
   */
  parts?: string[];
  /**
   * Глубина штампа, в единицах сцены. Пусто - по вещи. Отдельной детали
   * (двери) можно глубже: низ двери заваливается внутрь, а на соседние
   * детали печать всё равно не перелезет.
   */
  reach?: number;
  /**
   * Материалы, на которые ложится печать этого места, - вместо общих у вещи.
   * У дверей вана рамка окна - отдельная чёрная деталь, и без неё зона не
   * доходила до края двери.
   */
  surfaces?: string[];
  /**
   * Где в зоне оклейки стоит знак: центр и высота в долях высоты зоны от
   * верха. Без него - по центру. У кормы вана середина зоны приходится на
   * хромовую планку над номером, и она резала надпись пополам.
   */
  logo?: { y: number; h: number };
  /** Размер пятна на поверхности, в единицах модели. */
  size: [number, number];
};

/**
 * Клетка сетки - квадрат. Прямоугольник подсказывал бы, что место под
 * широкий логотип, а оно ни под какой: логотип любых пропорций вписывается
 * внутрь как есть. Сторона 0.05 при шаге рядов 0.08: зазор в шестьдесят
 * процентов стороны, и уголки соседних рядов не слипаются в одну рамку -
 * при 0.06 они сходились на волосок и читались решёткой из прямоугольников.
 */
const CELL: [number, number] = [0.05, 0.05];

/** Колонки слева направо. Угол подобран так, чтобы шаг столбцов на ткани
 * совпал с шагом рядов - решётка равносторонняя, а не вытянутая вширь. */
const COLUMNS = [-26, 0, 26];
/** Ряды сверху вниз: вторая, третья и четвёртая высоты прежней сетки. */
const ROWS = [0.63, 0.55, 0.47];

export const SPOTS: Spot[] = ROWS.flatMap((height, row) =>
  COLUMNS.map((azimuth, column) => {
    const number = row * COLUMNS.length + column + 1;
    const label = String(number).padStart(2, "0");
    return { code: `slot_${label}`, label, height, azimuth, size: CELL };
  }),
);

/**
 * Глубина коробки, которой декаль вырезается из поверхности. Было 0.12, и на
 * этом боковые пятна заворачивались на перёд: коробка на боку захватывала и
 * переднюю поверхность тоже, потому что там ткань круто уходит за угол. Ткань
 * тонкая, ей хватает малого.
 */
export const DECAL_DEPTH = 0.07;

/**
 * Чем перекрасить модель. Она приходит с запечённой текстурой чужого демо, а
 * нам нужна чистая вещь: на ней читаются наши места, а не чужой принт. Белый
 * не чистый, а с каплей серого: на чистом белом под этой выдержкой пропадают
 * складки, а вместе с ними и ощущение вещи.
 */
export const REPAINT = { color: 0xf1f2f5, roughness: 0.92 };

/**
 * Поля отметки места - доля от короткой стороны.
 *
 * Число одно на три места: по нему стоят уголки, по нему же вписывается
 * креатив и по нему же считаются углы мест для фото-режима. Разойдись они - и
 * креатив перестал бы совпадать с отметкой, а напечаталось бы не то, что
 * отмечено.
 */
export const FRAME_PAD = 0.06;

/**
 * Вещь для сцены: модель и её места. Сцена одна на все вещи, а различаются
 * они только этим.
 */
export type Shape = {
  /** Путь к модели в public приложения. */
  model: string;
  spots: Spot[];
  /** Глубина коробки декали - своя у каждой поверхности, см. DECAL_DEPTH. */
  depth: number;
  /**
   * Перекрасить ли вещь в белую ткань. Футболке это нужно: у модели чужой
   * запечённый принт. У чемодана свои материалы - корпус, колёса, ручка, - и
   * одна краска на всё сделала бы из него болванку.
   */
  cloth: boolean;
  /** Цвет ткани, если вещь перекрашивается в ткань не белого цвета. */
  paint?: number;
  /** Как вещь зовётся в подписях сцены: «Loading the shirt…». */
  noun: string;
  /**
   * На какие материалы модели ложатся места. Пусто - на все. У машины это
   * кузов и стёкла: места размечены по панелям целиком, вместе с арками, а
   * колёса, фары и решётка под ними остаются как есть.
   */
  surfaces?: string[];
  /** Цвет мест: пустого и выбранного. Пусто - общий рыжий. */
  mark?: { idle: number; hot: number };
  /**
   * Куда клеятся купленные стикеры: ячейки по очереди покупок и сколько
   * единиц сцены в сантиметре - стикер рисуется в настоящий размер.
   */
  stickers?: { slots: StickerSlot[]; centimeter: number };
};

/** Ячейка стикера: как у места - высота долей вещи, угол и сдвиг вбок. */
export type StickerSlot = { azimuth: number; height: number; shift: number };

export const SHIRT: Shape = {
  model: "/models/shirt.glb",
  spots: SPOTS,
  depth: DECAL_DEPTH,
  cloth: true,
  noun: "shirt",
};
