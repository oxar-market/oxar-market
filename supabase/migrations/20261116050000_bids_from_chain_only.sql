-- Ставку в базу пишет только функция record-bid - по подтверждённой
-- транзакции в цепочке.
--
-- Прежняя политика «ставит сам за себя» проверяла лишь, что ставишь от своего
-- имени в открытый торг. Подпись транзакции никто не сверял, и любой вошедший
-- одним запросом записывал ставку на любую сумму, ничего не заплатив: на
-- витрине вставал фальшивый лидер, честная ставка из цепочки отбивалась
-- триггером минимума, в печать ушёл бы чужой логотип, торг продлевался.
--
-- Теперь браузеру писать в lot_bids нельзя вовсе. Функция ходит под
-- service_role и пишет то, что прочитала из транзакции программы: кошелёк,
-- лот и сумму. Триггер bids_guard по-прежнему проверяет минимум и сроки.

drop policy "ставит сам за себя" on lot_bids;
revoke insert, update, delete on lot_bids from anon, authenticated;
