-- Как платят за это место: потоком или разом.
--
-- Поток хорош там, где есть автоматическая проверка: деньги идут по секундам,
-- пока размещение стоит, и останавливаются, когда оно пропало. Это про профиль
-- X, где состояние читается снимком.
--
-- Разовый перевод хорош там, где проверять нечем и у продавца есть невозвратная
-- трата до начала - печать футболки, например. Поток там не защищает
-- покупателя и бьёт по продавцу.
--
-- Поэтому это свойство места, а не всей платформы, и выбирает его продавец при
-- листинге. Умолчание - поток: так работало до сих пор, и менять поведение
-- существующих мест миграция не должна.

create type listing_payment as enum ('stream', 'transfer');

alter table public.listings
  add column payment listing_payment not null default 'stream';

comment on column public.listings.payment is
  'Поток по секундам или разовый перевод. Выбирает продавец при листинге';

-- Зоны футболки продаются разовым переводом: простой ткани проверить нечем, а
-- печать оплачена до начала.
update public.listings
set payment = 'transfer'
where kind in (select kind from public.placement_catalog where surface = 'tshirt');
