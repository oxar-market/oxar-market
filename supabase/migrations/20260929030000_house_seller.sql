-- Наши вещи получают продавца, чтобы их можно было оценить.
--
-- Оценка и счёт продавца держатся на things.seller: сделка - выигранный лот
-- на вещи с продавцом. У футболки и Shirt XX продавца не было, и их
-- победителям оценить было некого. Теперь продавец - владелец площадки.
--
-- Показывать эти вещи как вещи продавца нельзя: у них своя модель и места в
-- коде, а не снимки и разметка продавца. Поэтому «наша вещь» - отдельный
-- признак house, и экран смотрит на него, а не на пустоту seller.
--
-- Деньги это не трогает: получатель выплаты записан в торге в цепочке при
-- открытии, база его не выбирает.

alter table things add column house boolean not null default false;

update things set house = true where seller is null;

-- Владелец площадки: пользователь за кошельком AkC8…DtB, он же админ.
-- Нет такого пользователя (локальная база) - продавец остаётся пустым.
update things set seller = u.id
  from auth.users u
 where things.house and things.seller is null
   and u.id = '78e0f74a-3474-4f4b-875f-7030e18234fd';
