-- Подпись транзакции, которой торг разобрали: выплата победителя или
-- закрытие без него. До сих пор скрипт разбора её только печатал в лог, и
-- на экране итогов было нечем показать, что деньги действительно ушли.
-- Пусто у торгов, разобранных до этой колонки.
alter table lots
  add column settle_signature text
    check (settle_signature is null or length(settle_signature) between 64 and 100);
