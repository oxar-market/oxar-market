-- Оплаченный стикер - отметкой в базе.
--
-- Оплату знает только цепочка: строка стикера заводится до неё, и в таблице
-- лежат и черновики тех, кто загрузил логотип и не заплатил. Приложение
-- сверяет с цепочкой само, а лендингу и внешним витринам (разработчик
-- Burger) цепочка недоступна. Бот выплат и так ходит в цепочку каждые пару
-- минут: он и ставит здесь номер первой покупки и сколько стикеров в ней.
-- Номер - тот же, по которому приложение раскладывает стикеры на вещи,
-- поэтому на лендинге они встают на те же места.
alter table stickers
  add column paid_first integer,
  add column paid_count integer;

-- Покупатель отметку себе не поставит: строку он заводит без неё, а правок
-- у него нет вовсе. Ставит бот сервисным ключом.
drop policy "покупатель заводит свой стикер" on stickers;
create policy "покупатель заводит свой стикер" on stickers for insert
  with check (
    auth.uid() = buyer
    and paid_first is null
    and paid_count is null
    and exists (
      select 1 from things t where t.id = thing_id and t.sticker_sheet is not null
    )
  );
