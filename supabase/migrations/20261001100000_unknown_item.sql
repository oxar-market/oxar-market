-- Анонс на маркете: вторая наша вещь называется «Unknown item», а не «Shirt XX».
--
-- Что именно выйдет следующим, пока не говорим: на маркете вместо футболки
-- стоит знак вопроса, и имя не должно его выдавать. Ищем по slug - он не
-- меняется, - и только у нашей вещи.
update things
set title = 'Unknown item'
where slug = 'shirt-xx'
  and house;
