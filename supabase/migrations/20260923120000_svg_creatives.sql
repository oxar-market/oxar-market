-- Хранилище догоняет форму: SVG разрешён.
--
-- Форма ставки принимает image/svg+xml с самого начала, а bucket его резал -
-- человек выбирал файл и получал «Could not save» без единого слова почему.
-- Форматы обещают в одном месте, а решают в другом, и это второй такой случай
-- за неделю (первым был продавший форму лендинг), урок один: правило живёт в
-- хранилище, форма только повторяет его.
--
-- Для печати SVG - лучший из форматов: вектор не мылится ни на каком размере.
--
-- Видео из списка не трогаем: наследие прежнего маркетплейса, вопрос отдельный.

update storage.buckets
set allowed_mime_types = array[
  'image/png',
  'image/jpeg',
  'image/webp',
  'image/gif',
  'image/svg+xml',
  'video/mp4',
  'video/quicktime'
]
where id = 'creatives';
