-- Место на снимке - обведённая фигура, а не только прямоугольник.
--
-- Контур - точки в долях кадра, [[x, y], ...], от трёх до шестидесяти
-- четырёх (столько оставляет упрощение). Прямоугольник x, y, w, h остаётся
-- описанным вокруг контура: на нём держатся экран цен, размеры места на
-- модели и места, размеченные раньше прямоугольником.
alter table thing_spots
  add column outline jsonb check (
    outline is null
    or (jsonb_typeof(outline) = 'array' and jsonb_array_length(outline) between 3 and 64)
  );
