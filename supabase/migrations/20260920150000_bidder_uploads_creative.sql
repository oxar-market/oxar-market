-- Креатив в хранилище кладёт тот, кто ставит.
--
-- Прежняя политика пускала туда только «своих» - тех, кто есть в access_list
-- закрытого маркетплейса. Продукт теперь другой: ставить может любой вошедший,
-- а картинка едет вместе со ставкой, и без права на загрузку ставка осталась
-- бы без того, что напечатают.
--
-- Анониму по-прежнему нельзя: неподписанная загрузка превратила бы bucket в
-- бесплатный файлообменник. Ограничения самого bucket остаются на месте -
-- восемь мегабайт и список типов, - и они же держат размер.
--
-- Чтение открыто всем и трогать его незачем: креатив лидера видят все, в этом
-- и смысл торга.

drop policy if exists "insiders can upload a creative" on storage.objects;

create policy "вошедший кладёт креатив"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'creatives');
