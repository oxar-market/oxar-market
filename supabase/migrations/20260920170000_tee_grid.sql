-- Пятнадцать мест сеткой на переде вместо девяти по всей вещи.
--
-- Печать будет только спереди, поэтому спина, рукава и загривок из каталога
-- уходят: место, которого не напечатают, продавать нельзя.
--
-- Имена у мест теперь номера, а не части тела. Сетка на переде одинаковая, и
-- «Lower back» в ней называть нечего - зато «беру седьмое» произносится вслух
-- и одинаково читается в списке, на самой вещи и в разговоре.
--
-- Внешний ключ у lots стоит с on delete restrict, и здесь это не помеха, а
-- предохранитель: если на старом месте идёт торг, миграция упадёт громко, а не
-- снесёт аукцион молча. Открытые торги закрываются до выкатки, сознательно.
--
-- Коды повторяют разметку модели в коде (apps/app/app/auction/spots.ts), и
-- совпадение стережёт тест: разъедутся - место просто не найдётся на вещи.

delete from thing_spots
where code like 'tshirt\_%'
  and thing_id = (select id from things where slug = 'superteam-ua-tee');

insert into thing_spots (thing_id, code, label, sort)
select things.id, spot.code, spot.label, spot.sort
from things,
  (values
    ('slot_01', '01',  1),
    ('slot_02', '02',  2),
    ('slot_03', '03',  3),
    ('slot_04', '04',  4),
    ('slot_05', '05',  5),
    ('slot_06', '06',  6),
    ('slot_07', '07',  7),
    ('slot_08', '08',  8),
    ('slot_09', '09',  9),
    ('slot_10', '10', 10),
    ('slot_11', '11', 11),
    ('slot_12', '12', 12),
    ('slot_13', '13', 13),
    ('slot_14', '14', 14),
    ('slot_15', '15', 15)
  ) as spot (code, label, sort)
where things.slug = 'superteam-ua-tee'
on conflict (thing_id, code) do nothing;
