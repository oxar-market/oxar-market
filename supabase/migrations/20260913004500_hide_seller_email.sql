-- Почта продавца не для витрины.
--
-- Политика «verified sellers are public» отдаёт строку продавца целиком, а
-- значит и адрес для входа. Пока адреса не заполнены, это ничего не значило; с
-- первым же онбордингом контакты продавцов оказались бы в публичном API.
--
-- Снять права на одну колонку недостаточно: у anon и authenticated есть грант
-- на таблицу целиком, и он покрывает все колонки, включая новые. Поэтому
-- табличный грант снимается, а вместо него выдаётся список колонок. Адрес в
-- него не входит и не будет доступен никому, кроме security definer функции
-- owns_seller, которая по нему и проверяет владельца.
--
-- Побочное следствие: select=* от анонима теперь не работает, колонки надо
-- перечислять. Витрина их и так перечисляет.

revoke select on public.sellers from anon, authenticated;

grant select (
  id,
  created_at,
  x_handle,
  display_name,
  follower_count,
  bio,
  avatar_url,
  verified,
  is_org
) on public.sellers to anon, authenticated;
