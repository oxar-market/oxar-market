-- Шаг ставки на галстук - $25, а не $5.
--
-- Лот открыт скриптом с шагом $5, и в программе он так и остался: поменять
-- шаг у открытого лота программа не даёт. Сайт считает минимум следующей
-- ставки по этой строке, поэтому шаг $25 держит он. Он строже программы -
-- там шаг не меньше max(5%, $5), - значит любая ставка с сайта программе
-- подходит. Решение Даниила 13 октября 2026: старт $150, шаг $25.
update lots
set min_step_cents = 2500
where id = '38b456ed-5902-4bc3-8c4e-b174ba1f3d5b'
  and min_step_cents = 500;
