-- Покупатель видит свои брони.
--
-- До этого на bookings была одна политика чтения - для продавца, на заявки по
-- его местам. Покупатель не видел собственную заявку вообще, и это ломало не
-- только интерфейс.
--
-- При включённом RLS запрос вида `update ... where id = ...` ограничен и
-- политикой обновления, и политикой чтения: строку сначала надо найти. Без
-- права читать своё покупатель получал на привязку кошелька честный 204 и ноль
-- изменённых строк - то есть тихий отказ, который выглядит как успех.
--
-- Видно ему только своё: адрес в брони сверяется с адресом из токена. Чужие
-- заявки с контактами и суммами по-прежнему видны только продавцу места.

create policy "buyer reads own bookings"
  on public.bookings for select to authenticated
  using (
    buyer_email is not null
    and lower(buyer_email) = lower(auth.jwt() ->> 'email')
  );
