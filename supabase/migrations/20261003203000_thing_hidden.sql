-- Спрятать вещь с маркета - не то же, что её не одобрить. До сих пор
-- «Hide from market» просто снимал active, и спрятанная вещь выглядела в
-- админке как ждущая одобрения: с кнопками Approve и Decline, хотя торг по
-- ней уже идёт в цепочке. Нашли на живом торге 3 октября 2026.
--
-- Флаг ставит и снимает только админ: правит вещи одна политика «админ
-- правит вещи» (is_admin()), у продавца update нет вовсе, а его функции
-- пишут лишь название и «кто, где, когда». Маркет флаг не читает: показ
-- по-прежнему решает active.
alter table things
  add column hidden boolean not null default false;

-- Остаётся вставка: продавец заводит вещь сам, и политика проверяла только
-- автора. Вещь с hidden = true выглядела бы у админа одобренной и
-- спрятанной, и «Show on Market» вывел бы её на маркет без одобрения. А
-- active по умолчанию true с самого начала, так что продавец мог миновать
-- проверку и прямой вставкой. Новая вещь рождается неодобренной и
-- неспрятанной - приложение и так вставляет active = false.
drop policy if exists "одобренный продавец заводит вещь" on things;
create policy "одобренный продавец заводит вещь" on things for insert
  with check (
    seller = auth.uid()
    and not active
    and not hidden
    and exists (
      select 1 from profiles p where p.user_id = auth.uid() and p.is_seller
    )
  );
