-- Тестовая вещь, выставленная 29.09 с прода, чтобы проверить кабинет:
-- «New thing No. 1» на шести местах. Торг в цепочке на неё не открывался,
-- поэтому удаляется целиком из базы: черновики лотов, места, сама вещь.
-- Если хоть один лот уже не черновик - значит торг ушёл в цепочку, и
-- миграция останавливается, ничего не трогая. Проверка и удаление в одном
-- блоке: ошибка проверки не даст дойти до удаления, как бы ни запускали файл.
do $$
begin
  if exists (
    select 1 from lots
     where thing_id = '77bee68b-0df4-4a22-a011-125d6c196489' and status <> 'draft'
  ) then
    raise exception 'у тестовой вещи есть открытый торг - удалять нельзя';
  end if;

  delete from lots where thing_id = '77bee68b-0df4-4a22-a011-125d6c196489';
  delete from things where id = '77bee68b-0df4-4a22-a011-125d6c196489';
end $$;
