-- Чемодан: пять мест на лицевой грани.
--
-- Ровно тот случай, ради которого каталог сделан данными: новая вещь - это
-- пять строк, а не правка типа и выкладка кода. Ни аукцион, ни фикс-прайс, ни
-- поденная оплата об этом не знают, они смотрят на листинг.
--
-- Почему только лицевая грань. Из четырёх сторон плоская и пустая она одна: на
-- противоположной идёт телескопическая ручка, две оставшиеся узкие и со швом
-- посередине. Разметка снята с модели лучами, подробности в Suitcase.tsx.
--
-- Доказательство - фотография, как и у футболки: у вещи нет ни строки, ни
-- картинки профиля, ни id поста, проверить размещение может только человек.
--
-- Срок по умолчанию неделя, а не три дня как у футболки: футболку надевают на
-- конференцию, а с чемоданом ездят всю поездку.

