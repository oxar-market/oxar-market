-- Аукционы закрываются по расписанию, а не когда кто-то откроет страницу.
--
-- До этого `close_due_auctions` дёргался только из браузера, из XProfile и
-- SellerDesk, перед чтением списка лотов. Значит торг с истёкшим сроком висел
-- открытым, пока на сайт кто-нибудь не зайдёт: ночью - до утра. Победитель не
-- получал бронь, а продавец не видел сделки.
--
-- Функция уже security definer и возвращает число закрытых лотов, так что
-- планировщику остаётся её звать. Раз в пять минут: точность аукциона меряется
-- минутами, а не секундами, и при пустой очереди вызов стоит один запрос к
-- индексу.
--
-- Вызов из браузера оставлен намеренно. Он стал подстраховкой, а не механизмом:
-- если планировщик встанет, лоты всё равно закроются у первого посетителя.

create extension if not exists pg_cron;

-- Повторный запуск миграции не плодит задания: расписание заводится по имени и
-- перезаписывается.
select cron.schedule(
  'close-due-auctions',
  '*/5 * * * *',
  $$select public.close_due_auctions()$$
);
